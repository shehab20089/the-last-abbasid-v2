const SPACE_ADVANCE = 3;

function buildFont(name, scale, bevel) {
  const chars = Object.keys(G);
  const cellH = 9 * scale;
  const pad = 1 + (bevel ? 1 : 0);
  const columns = 16;
  const widths = chars.map((ch) => Math.max(...G[ch].map((r) => r.length)) * scale);
  const cellW = Math.max(...widths) + pad * 2;
  const rows = Math.ceil(chars.length / columns);
  const atlas = new Canvas(columns * cellW, rows * (cellH + pad * 2));
  const ink = [244, 236, 220, 255];
  const shade = [168, 150, 128, 255];
  const records = [];
  chars.forEach((ch, i) => {
    const glyph = G[ch];
    const ox = (i % columns) * cellW + pad;
    const oy = Math.floor(i / columns) * (cellH + pad * 2) + pad;
    const w = widths[i];
    for (let r = 0; r < glyph.length; r++) {
      for (let c = 0; c < glyph[r].length; c++) {
        if (glyph[r][c] !== "#") continue;
        for (let sy = 0; sy < scale; sy++) {
          for (let sx = 0; sx < scale; sx++) {
            // The title face is bevelled: the lower half of each stroke is a shade darker.
            const color = bevel && sy >= scale / 2 ? shade : ink;
            atlas.set(ox + c * scale + sx, oy + r * scale + sy, color);
          }
        }
      }
    }
    records.push({ id: ch.codePointAt(0), x: ox, y: oy, width: w, height: cellH, xadvance: w + scale });
  });
  const lineHeight = 11 * scale;
  const base = 7 * scale;
  const lines = [
    `info face="${name}" size=${cellH} bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1`,
    `common lineHeight=${lineHeight} base=${base} scaleW=${atlas.width} scaleH=${atlas.height} pages=1 packed=0`,
    `page id=0 file="${name}.png"`,
    `chars count=${records.length + 1}`,
    `char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance=${SPACE_ADVANCE * scale} page=0 chnl=15`,
    ...records.map((r) => `char id=${r.id} x=${r.x} y=${r.y} width=${r.width} height=${r.height} xoffset=0 yoffset=0 xadvance=${r.xadvance} page=0 chnl=15`),
  ];
  mkdirSync(OUT, { recursive: true });
  atlas.save(join(OUT, `${name}.png`));
  writeFileSync(join(OUT, `${name}.fnt`), lines.join("\n") + "\n");
  return atlas;
}

